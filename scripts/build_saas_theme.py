#!/usr/bin/env python3
"""Build public/saas_theme/css/saas_theme.css from css/src/*.css.

The theme is served as ONE file (services/ui_apps.py loads a single content-hashed URL),
and the bench has no asset pipeline for it, so the partials are concatenated here and the
result is committed. Edit css/src/*, run this script, commit both.

    python3 scripts/build_saas_theme.py          # write
    python3 scripts/build_saas_theme.py --check  # exit 1 if the committed file is stale
"""
import sys
from pathlib import Path

CSS_DIR = Path(__file__).resolve().parent.parent / "zatgo_core" / "public" / "saas_theme" / "css"
OUT = CSS_DIR / "saas_theme.css"
BANNER = "/* GENERATED by scripts/build_saas_theme.py from css/src/*.css — edit the partials, not this file. */\n"


def build() -> str:
	parts = sorted((CSS_DIR / "src").glob("*.css"))
	return BANNER + "".join(p.read_text(encoding="utf-8") for p in parts)


if __name__ == "__main__":
	built = build()
	if "--check" in sys.argv:
		sys.exit(0 if OUT.read_text(encoding="utf-8") == built else 1)
	OUT.write_text(built, encoding="utf-8")
	print(f"wrote {OUT} ({len(built.splitlines())} lines)")
